def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    by_id = {s["id"]: s for s in data["streams"]}
    added = 0
    for row in NEW:
        if row["id"] in by_id:
            # refresh provider / note if already present
            cur = by_id[row["id"]]
            cur["provider"] = row["provider"]
            cur["embed"] = True
            cur["verify"] = False
            cur["note"] = row["note"]
            cur["operator"] = row["operator"]
            continue
        data["streams"].append(row)
        added += 1
    # Ensure existing explore cams carry explore_url homepage when missing
    for s in data["streams"]:
        if "explore.org" in (s.get("operator") or "").lower():
            p = s.setdefault("provider", {})
            if p.get("type") == "youtube_video" and not p.get("explore_url"):
                p["explore_url"] = EXPLORE
    data["as_of"] = "2026-10-17"
    data["note"] = (
        "Explore.org Oceans cams integrated from https://explore.org/livecams/oceans/ "
        "(YouTube live ids confirmed 2026-10-17). ONC schedules from oceannetworks.ca. "
        "Update via scripts/healthcheck_streams.py and scripts/integrate_explore_oceans.py."
    )
    data["sources"] = {
        "explore_oceans": EXPLORE,
        "explore_youtube_channels": "https://explore.org/youtube-channels",
        "onc_live_cameras": "https://www.oceannetworks.ca/multimedia/live-cameras/",
    }
    PATH.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    n_yt = sum(1 for s in data["streams"] if s.get("provider", {}).get("type") == "youtube_video")
    print(f"streams={len(data['streams'])} youtube_embeds={n_yt} newly_added={added}")


if __name__ == "__main__":
    main()
